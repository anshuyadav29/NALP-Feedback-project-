#!/usr/bin/env bash
# deploy/lib/stack.sh — installing and starting the compose stack on the target

if [[ -n "${_STACK_LOADED:-}" ]]; then
  return 0
fi
readonly _STACK_LOADED=1

if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
  echo "error: This file is a library and must be sourced, not executed." >&2
  exit 1
fi

# Creates the stack's secrets exactly once. Re-running the deployment must not
# rotate them: a new database password would lock out the existing volume, and a
# new MCP token would silently break every client already configured with it.
stack_ensure_env() {
  local image="$1"
  local remote_env="${REMOTE_DIR}/.env"

  if remote_path_exists "${remote_env}"; then
    msg "  reusing existing secrets from ~/${remote_env}"
    stack_update_env "${image}"
    return 0
  fi

  msg "  generating secrets (first deployment)"
  local db_password mcp_token
  db_password="$(openssl rand -hex 24)"
  mcp_token="$(openssl rand -hex 32)"

  # Passed through stdin rather than as arguments, which would be visible in the
  # target's process list, and created with mode 600 before content lands in it.
  remote_write_file "${remote_env}" 600 <<EOF
# Generated by deploy.sh on first deployment. Keep this file — losing the
# database password makes the existing volume unreadable.
APP_IMAGE=${image}
DB_NAME=issuetracker
DB_USER=issuetracker
DB_PASSWORD=${db_password}
MCP_AUTH_TOKEN=${mcp_token}
PUBLIC_HOSTS=${PUBLIC_HOSTS}
PUBLIC_ORIGINS=${PUBLIC_ORIGINS}
EOF
}

# Refreshes the values that may change between deployments. The host list matters:
# a changed --public-host would otherwise leave the MCP endpoint answering 421
# for the new name.
stack_update_env() {
  local image="$1"
  local remote_env="${REMOTE_DIR}/.env"

  remote_run "sed -i \
    -e 's|^APP_IMAGE=.*|APP_IMAGE=${image}|' \
    -e 's|^PUBLIC_HOSTS=.*|PUBLIC_HOSTS=${PUBLIC_HOSTS}|' \
    -e 's|^PUBLIC_ORIGINS=.*|PUBLIC_ORIGINS=${PUBLIC_ORIGINS}|' \
    '${remote_env}'"
}

stack_install() {
  local image="$1"

  step "Installing stack on ${REMOTE_TARGET}"
  remote_run "mkdir -p '${REMOTE_DIR}'"
  remote_copy "${SCRIPT_DIR}/compose.yml" "${REMOTE_DIR}/compose.yml"
  remote_copy "${SCRIPT_DIR}/nginx.conf" "${REMOTE_DIR}/nginx.conf"
  stack_ensure_env "${image}"

  step "Starting containers"
  remote_run "cd '${REMOTE_DIR}' && sudo -n docker compose up -d --remove-orphans"
}

# Publishes the chosen name over mDNS. Avahi answers for its own host name only,
# so a name below it needs an explicit alias record.
stack_publish_mdns() {
  if [[ "${SKIP_MDNS}" == "true" ]]; then
    msg "  mDNS alias skipped on request"
    return 0
  fi

  step "Publishing mDNS alias ${PUBLIC_HOST}"

  if ! remote_run 'command -v avahi-publish' >/dev/null 2>&1; then
    msg "  installing avahi-utils"
    if ! remote_sudo "DEBIAN_FRONTEND=noninteractive apt-get install -y -qq avahi-utils" >/dev/null 2>&1; then
      warn "Could not install avahi-utils — reach the tracker by IP instead."
      return 0
    fi
  fi

  remote_write_file "/tmp/issue-tracker-mdns.service" 644 <<EOF
[Unit]
Description=Publish mDNS alias ${PUBLIC_HOST}
After=network-online.target avahi-daemon.service
Wants=network-online.target avahi-daemon.service

[Service]
# The address is fixed at deploy time; re-run the deployment if the host's IP changes.
ExecStart=/usr/bin/avahi-publish -a -R ${PUBLIC_HOST} ${TARGET_ADDRESS}
Restart=always
RestartSec=5

[Install]
WantedBy=multi-user.target
EOF

  remote_sudo "install -m 644 /tmp/issue-tracker-mdns.service /etc/systemd/system/issue-tracker-mdns.service"
  remote_sudo "systemctl daemon-reload"

  if ! remote_sudo "systemctl enable --now issue-tracker-mdns.service" >/dev/null 2>&1; then
    warn "Could not enable the mDNS alias service — reach the tracker by IP instead."
  fi

  remote_run "rm -f /tmp/issue-tracker-mdns.service"
}
